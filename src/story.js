// 프롤로그 컷 목록. 퍼즐 게임은 말을 몰라도 할 수 있어야 하므로, 프롤로그는 글 없이 그림만 보고 이해할 수 있게 만든다.
// 컷 그림은 assets/asset-list.js의 story-1 ~ story-6이고, 그림이 오기 전에는 game.js가 회색 상자 위에 scene 설명을 보여 준다.
// 컷 순서는 docs/mockup/water-spirit.html의 회색 상자 여섯 컷을 따른다(2026-10-28).
// 4컷이 "정령이 왜 대놓고 맞서지 못하는가"를 보여 주고, 6컷이 "얼음을 뱉으면 돌이 밀린다"는 규칙을 한 번 시연한다.
(function (root) {
  'use strict';

  // 회색 상자 위의 장면 설명이 "펌프 / 관"처럼 구절 중간에서 꺾이지 않게, 묶을 구절의 띄어쓰기를 줄바꿈 없는 공백으로 바꾼다.
  const nw = (phrase) => phrase.replace(/ /g, ' ');

  // scene은 그림을 그릴 때의 장면 설명이다(게임에는 그림이 없을 때만 보인다).
  const prologue = [
    {
      key: 'story-1',
      scene: `숲속 작은 샘. 물빛 몸의 정령이 샘물에 허리까지 ${nw('담근 채')} 편히 ${nw('쉬고 있다.')} `
        + `샘가의 ${nw('물길 돌이')} ${nw('샘 입구')} 홈에 ${nw('끼워져 있고,')} ${nw('그 너머로')} 맑은 물줄기가 숲으로 흘러간다.`,
    },
    {
      key: 'story-2',
      scene: `마을 사람들이 ${nw('샘 입구에')} 녹슨 ${nw('펌프 관을')} ${nw('박아 넣는다.')} 한 사람은 홈에서 뽑은 ${nw('물길 돌을')} `
        + `${nw('어깨 너머로')} 던지고, 돌은 포물선을 그리며 샘가 풀숲으로 떨어진다. 정령은 물속에서 ${nw('눈만 내놓고')} 지켜본다.`,
    },
    {
      key: 'story-3',
      scene: `샘물이 관을 따라 마을 쪽으로 ${nw('빨려 나가')} 샘의 물높이가 눈에 띄게 낮아졌다(젖은 자국이 돌에 ${nw('남아 있다).')} `
        + `정령의 몸은 ${nw('1컷의 절반')} 크기로 작아지고 흐리게 비친다.`,
    },
    {
      key: 'story-4',
      scene: `작아진 정령이 관 옆에 선 샘지기에게 다가가려다 멈춰 ${nw('바위 뒤로')} ${nw('몸을 숨긴다.')} `
        + `샘지기는 마개를 연 ${nw('빈 유리병을')} 손에 들고 샘을 내려다본다. ${nw('병 속에는')} 이미 작은 물빛 ${nw('정령 하나가')} ${nw('갇혀 있다.')}`,
    },
    {
      key: 'story-5',
      scene: `${nw('바위 뒤의')} 정령이 눈을 가늘게 뜨고 조용히 결심한다. 볼에 머금은 ${nw('몸의 물 한 줌이')} `
        + `입가에서 하얗게 얼어붙어 ${nw('얼음 조각이')} 된다.`,
    },
    {
      // 시연 컷. 플레이 화면만으로는 뱉기가 무엇을 하는지 전해지지 않아서, 얼음을 뱉으면 돌이 밀려 홈에 들어간다는 것을 한 컷에 보여 준다.
      key: 'story-6',
      scene: `한 컷 안의 연속 동작을 왼쪽에서 오른쪽으로 읽는다. 왼쪽에서 정령이 볼을 불룩하게 한 채 ${nw('고개를 내밀고,')} `
        + `가운데에서 입에서 튀어나간 ${nw('얼음 조각이')} 속도선을 그리며 수평으로 날아가고, 오른쪽에서 얼음에 맞은 ${nw('물길 돌이')} `
        + `샘가 땅 위를 미끄러져 ${nw('샘 입구 돌벽의')} ${nw('빈 홈에')} ${nw('쏙 들어간다.')} `
        + `${nw('돌이 미끄러진')} 길에는 ${nw('움직임 선을')} 그린다.`,
    },
  ];

  root.Story = { prologue };
})(window);
